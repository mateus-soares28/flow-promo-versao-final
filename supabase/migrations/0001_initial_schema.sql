create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;
create trigger profiles_updated_at before update on public.profiles for each row execute function public.set_updated_at();
create trigger integration_connections_updated_at before update on public.integration_connections for each row execute function public.set_updated_at();
create trigger whatsapp_sessions_updated_at before update on public.whatsapp_sessions for each row execute function public.set_updated_at();

-- Cria o perfil automaticamente quando um usuário nasce no Supabase Auth.
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, name, role)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'name', new.email), 'user')
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- RLS: o usuário acessa somente os próprios registros; admins podem acessar tudo via policies específicas.
