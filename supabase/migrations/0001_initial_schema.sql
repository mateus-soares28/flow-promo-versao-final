create table public.segments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id bigint unique,
  name text not null,
  store public.store_code not null default 'all',
  keywords text not null,
  min_discount_percentage integer not null default 15,
  min_quality_score integer not null default 60,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.offers (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  legacy_id bigint unique,
  store text not null,
  title text not null,
  category text,
  original_price integer not null,
  promo_price integer not null,
  discount_percent integer not null,
  coupon text,
  free_shipping boolean not null default false,
  verified_seller boolean not null default true,
  quality_score integer not null default 85,
  original_url text not null,
  affiliate_url text not null,
  image_url text,
  status public.offer_status not null default 'detected',
  created_at timestamptz not null default now()
);

create table public.dispatches (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id bigint unique,
  offer_id bigint references public.offers(id) on delete set null,
  group_id bigint references public.affiliate_groups(id) on delete set null,
  message_content text not null,
  status public.dispatch_status not null default 'pending',
  scheduled_for timestamptz not null default now(),
  sent_at timestamptz,
  error_message text,
  created_at timestamptz not null default now()
);

