-- FlowPromos: migração de Drizzle/MySQL para Supabase/PostgreSQL
-- A tabela public.profiles representa a antiga users e usa o UUID do Supabase Auth.
-- legacy_id/open_id preservam referências para uma importação gradual dos dados atuais.

create extension if not exists pgcrypto;

create type public.user_role as enum ('user', 'admin');
create type public.user_status as enum ('active', 'suspended', 'pending');
create type public.plan_code as enum ('none', 'essencial', 'pro', 'expert', 'anual');
create type public.plan_status as enum ('trial', 'active', 'cancelled', 'expired');
create type public.integration_provider as enum ('whatsapp', 'telegram', 'amazon', 'shopee', 'mercadolivre');
create type public.integration_status as enum ('connected', 'disconnected', 'error');
create type public.billing_cycle as enum ('monthly', 'annual');
create type public.subscription_status as enum ('active', 'pending', 'past_due', 'cancelled');
create type public.subscription_change_status as enum ('completed', 'failed');
create type public.whatsapp_status as enum ('disconnected', 'connecting', 'connected');
create type public.group_platform as enum ('whatsapp', 'telegram');
create type public.store_code as enum ('all', 'shopee', 'amazon', 'magalu', 'mercadolivre', 'aliexpress');
create type public.offer_status as enum ('detected', 'scheduled', 'sent', 'ignored');
create type public.dispatch_status as enum ('pending', 'processing', 'sent', 'failed');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id bigint unique,
  open_id text unique,
  name text,
  email text,
  password_hash text,
  login_method text not null default 'supabase_auth',
  role public.user_role not null default 'user',
  status public.user_status not null default 'active',
  plan public.plan_code not null default 'none',
  plan_status public.plan_status not null default 'trial',
  expires_at timestamptz,
  whatsapp_number text,
  shopee_tag text,
  amazon_tag text,
  magalu_tag text,
  aliexpress_tag text,
  mercado_livre_tag text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in timestamptz
);

create table public.plans (
  id text primary key,
  name text not null,
  description text,
  price_monthly integer not null,
  price_annual integer not null,
  offers_limit_per_day integer not null,
  groups_limit integer not null,
  channels_limit integer not null,
  quality_score_max integer not null,
  stores_limit integer not null,
  is_popular boolean not null default false,
  stripe_price_id_monthly text,
  stripe_price_id_annual text
);

create table public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id bigint unique,
  plan_id text not null references public.plans(id),
  billing_cycle public.billing_cycle not null default 'annual',
  status public.subscription_status not null default 'pending',
  amount integer not null,
  payment_method text default 'stripe_card',
  stripe_subscription_id text unique,
  stripe_customer_id text,
  start_date timestamptz not null default now(),
  end_date timestamptz not null,
  created_at timestamptz not null default now()
);

create table public.subscription_changes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  subscription_id bigint not null references public.subscriptions(id) on delete cascade,
  from_cycle public.billing_cycle,
  to_cycle public.billing_cycle not null,
  amount integer not null,
  status public.subscription_change_status not null default 'completed',
  source text not null default 'stripe',
  stripe_subscription_id text,
  created_at timestamptz not null default now()
);

create table public.integration_connections (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  provider public.integration_provider not null,
  encrypted_credentials text not null,
  status public.integration_status not null default 'connected',
  last_error text,
  last_tested_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, provider)
);

create table public.whatsapp_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  session_name text not null,
  status public.whatsapp_status not null default 'disconnected',
  phone text,
  qr_code_url text,
  last_seen timestamptz,
  updated_at timestamptz not null default now()
);

create table public.affiliate_groups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  legacy_id bigint unique,
  platform public.group_platform not null default 'whatsapp',
  group_id text not null,
  name text not null,
  segment text default 'Geral',
  is_active boolean not null default true,
  members_count integer not null default 0,
  created_at timestamptz not null default now()
