alter table public.subscription_changes enable row level security;
alter table public.integration_connections enable row level security;
alter table public.whatsapp_sessions enable row level security;
alter table public.affiliate_groups enable row level security;
alter table public.segments enable row level security;
alter table public.offers enable row level security;
alter table public.dispatches enable row level security;

create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

create policy profiles_self_or_admin on public.profiles for select using (id = auth.uid() or public.is_admin());
create policy profiles_self_update on public.profiles for update using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());
create policy plans_authenticated_read on public.plans for select to authenticated using (true);

create policy subscriptions_owner_or_admin on public.subscriptions for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy subscription_changes_owner_or_admin on public.subscription_changes for select using (user_id = auth.uid() or public.is_admin());
create policy integration_owner_or_admin on public.integration_connections for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy whatsapp_owner_or_admin on public.whatsapp_sessions for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy groups_owner_or_admin on public.affiliate_groups for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy segments_owner_or_admin on public.segments for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy offers_owner_or_admin on public.offers for all using (user_id = auth.uid() or user_id is null or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy dispatches_owner_or_admin on public.dispatches for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());

comment on table public.profiles is 'Migrated from Drizzle users; id is Supabase Auth UUID and legacy_id maps the old integer id.';
comment on table public.subscription_changes is 'History of monthly/annual subscription changes, including Stripe failures.';
