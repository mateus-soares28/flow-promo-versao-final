begin;

create table if not exists public.group_member_snapshots (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  group_id bigint not null references public.affiliate_groups(id) on delete cascade,
  members_count integer not null check (members_count >= 0),
  recorded_at timestamptz not null default now()
);

create index if not exists group_member_snapshots_history_idx
  on public.group_member_snapshots(user_id, group_id, recorded_at desc);

alter table public.group_member_snapshots enable row level security;

create policy group_member_snapshots_owner_or_admin
  on public.group_member_snapshots for all
  using (user_id = auth.uid() or public.is_admin())
  with check (user_id = auth.uid() or public.is_admin());

create or replace function public.get_group_growth_24h()
returns table (current_members bigint, previous_members bigint, compared_groups bigint)
language sql stable security invoker set search_path = public as $$
  with latest as (
    select distinct on (group_id) group_id, members_count, recorded_at
    from public.group_member_snapshots
    where user_id = auth.uid()
    order by group_id, recorded_at desc
  ), baseline as (
    select distinct on (group_id) group_id, members_count
    from public.group_member_snapshots
    where user_id = auth.uid() and recorded_at <= now() - interval '24 hours'
    order by group_id, recorded_at desc
  )
  select coalesce(sum(latest.members_count), 0)::bigint,
         coalesce(sum(baseline.members_count), 0)::bigint,
         count(*)::bigint
  from latest join baseline using (group_id)
  where latest.recorded_at > now() - interval '24 hours';
$$;

grant execute on function public.get_group_growth_24h() to authenticated;

commit;
